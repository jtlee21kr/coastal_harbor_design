# =====================================================================
st.header("📌 항만 설계 일반사항 (General Design Principles)")

col1, col2 = st.columns(2, gap="large")

with col1:
    st.subheader("1. 항만 구조물의 목적과 분류")
    st.markdown("""
    항만 구조물은 선박의 안전한 정박, 하역, 그리고 해일이나 파랑으로부터 항내를 보호하기 위해 축조되는 핵심 해양 인프라입니다.

    *   **외곽 시설 (Breakwaters) :** 방파제, 방사제 등 항외로부터 밀려오는 파랑을 막아 항내 정온도를 유지합니다.
    *   **계류 시설 (Mooring Facilities) :** 안벽(Quay Wall), 물양장, 잔교 등 선박이 접안하여 화물 및 여객을 처리하는 주요 하역 시설입니다.
    *   **수역 시설 (Waterways) :** 항로, 선회장, 정박지 등 선박의 안전한 운항을 위한 필수 수역입니다.
    """)

    st.subheader("2. 주요 설계 외력 및 환경 조건")
    st.markdown("""
    해양에 건설되는 구조물의 특성상 육상 구조물보다 가혹하고 복잡한 자연조건을 고려하여 안정성을 확보해야 합니다.

    *   **기상 및 해상 조건 :** 설계파고, 파주기, 풍속, 조위(H.W.L, L.L.W, R.W.L 등), 조류 및 해일.
    *   **지반 조건 :** 해저 지반의 기초 지지력, 압밀 침하 특성, 연약지반 유무, 흙의 전단강도 및 마찰각.
    *   **지진 하중 :** 설계수평지진계수($k_h$)에 따른 관성력 및 동수압, 동토압(M-O 이론 등)의 반영.
    *   **특수 하중 :** 선박 접안 시 발생하는 충격력, 계선주 견인력, 크레인 및 트럭 등에 의한 상재하중.
    """)

with col2:
    st.subheader("3. 안벽(Quay Wall)의 구조 형식")
    st.markdown("""
    설계 대상지의 수심, 해저 지반 조건, 시공성 및 경제성에 따라 적합한 구조 형식을 선정합니다.

    *   **중력식 안벽 (Gravity Type):**
        *   **특징 :** 구조물 자체의 자중으로 배면의 토압과 수압 등 외력에 저항하는 가장 전통적이고 안정적인 형식입니다.
        *   **종류 :** **콘크리트 블록식 (본 시스템 제공)**, 케이슨식, 셀룰러블록식 등.
        *   **적용 :** 양호한 지지기층(사석 마운드) 확보가 용이한 곳에 주로 적용됩니다.
    *   **널말뚝식 안벽 (Sheet Pile Type):**
        *   **특징 :** 강관 또는 철근콘크리트 널말뚝을 연속으로 항타하여 흙막이벽을 형성하는 형식입니다.
        *   **적용 :** 지반이 비교적 연약하고 수심이 깊지 않은 곳에 경제적으로 적용 가능합니다.
    *   **잔교식 안벽 (Pier Type):**
        *   **특징 :** 해저에 말뚝을 박고 그 위에 상부공(Slab)을 얹어 구조물을 지지하는 형식입니다.
        *   **적용 :** 지반이 매우 연약하거나 수심이 깊은 곳에 주로 사용됩니다.
    """)

